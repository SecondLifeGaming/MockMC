package org.mockmc.metaminer.diff;

import java.io.File;
import java.io.IOException;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Deterministic Markdown report generator for pairwise compatibility diffs.
 * Generates both summary compatibility documentation (e.g. COMPAT.md) and
 * granular platform transition reports.
 */
public final class CompatMarkdownRenderer {

	private CompatMarkdownRenderer() {}

	public static void renderToMarkdown(
			PairwiseDiff diff,
			File outputFile,
			String primaryJarName,
			String fallbackJarName
	) throws IOException {
		try (PrintWriter out = new PrintWriter(outputFile, StandardCharsets.UTF_8)) {
			out.println("# API Compatibility Report");
			out.println();
			out.println("> Generated by `VersionDiffEngine`. Do not edit manually.");
			out.println();
			if (primaryJarName != null) {
				out.println("- **Primary API** (wins at compile time): `" + primaryJarName + "`");
			}
			if (fallbackJarName != null) {
				out.println("- **Fallback API** (fills gaps only): `" + fallbackJarName + "`");
			}
			out.println("- **Comparison**: `" + diff.fromVersion() + "` \u2192 `" + diff.toVersion() + "`");
			out.println();

			out.println("| Category | Count |");
			out.println("| --- | --- |");
			out.println("| Binary Incompatible Changes | " + diff.summary().binaryIncompatibleChanges() + " |");
			out.println("| Source Incompatible Changes | " + diff.summary().sourceIncompatibleChanges() + " |");
			out.println("| Compatible Additions | " + diff.summary().compatibleAdditions() + " |");
			out.println("| Deprecations | " + diff.summary().deprecations() + " |");
			out.println("| Total API Changes | " + diff.summary().totalChanges() + " |");
			out.println();

			// Group changes by category
			List<PairwiseDiff.ChangeEntry> binaryBreaks = new ArrayList<>();
			List<PairwiseDiff.ChangeEntry> additions = new ArrayList<>();
			List<PairwiseDiff.ChangeEntry> deprecations = new ArrayList<>();
			List<PairwiseDiff.ChangeEntry> other = new ArrayList<>();

			for (PairwiseDiff.ChangeEntry change : diff.changes()) {
				switch (change.compatibilityImpact()) {
					case BINARY_INCOMPATIBLE -> binaryBreaks.add(change);
					case COMPATIBLE_ADDITION -> additions.add(change);
					case NON_BREAKING_DEPRECATION -> deprecations.add(change);
					default -> other.add(change);
				}
			}

			if (!binaryBreaks.isEmpty()) {
				out.println("## Binary Incompatible Changes");
				out.println();
				out.println("Breaking changes requiring recompilation or plugin code updates.");
				out.println();
				writeGroupedChanges(out, binaryBreaks);
			}

			if (!additions.isEmpty()) {
				out.println("## Compatible Additions");
				out.println();
				out.println("New API classes, methods, and default implementations added upstream.");
				out.println();
				writeGroupedChanges(out, additions);
			}

			if (!deprecations.isEmpty()) {
				out.println("## Newly Deprecated APIs");
				out.println();
				out.println("APIs marked with `@Deprecated` upstream in `" + diff.toVersion() + "`.");
				out.println();
				writeGroupedChanges(out, deprecations);
			}

			if (!other.isEmpty()) {
				out.println("## Other API Modifications");
				out.println();
				writeGroupedChanges(out, other);
			}
		}
	}

	private static void writeGroupedChanges(PrintWriter out, List<PairwiseDiff.ChangeEntry> entries) {
		Map<String, List<PairwiseDiff.ChangeEntry>> byClass = new TreeMap<>();
		for (PairwiseDiff.ChangeEntry entry : entries) {
			String className;
			if (entry.type() == PairwiseDiff.SymbolType.CLASS) {
				className = entry.symbol();
			} else {
				int hashIdx = entry.symbol().indexOf('#');
				className = hashIdx > 0 ? entry.symbol().substring(0, hashIdx) : entry.symbol();
			}
			byClass.computeIfAbsent(className, _ -> new ArrayList<>()).add(entry);
		}

		for (Map.Entry<String, List<PairwiseDiff.ChangeEntry>> classEntry : byClass.entrySet()) {
			out.println("### `" + classEntry.getKey() + "`");
			out.println();
			for (PairwiseDiff.ChangeEntry item : classEntry.getValue()) {
				if (item.type() == PairwiseDiff.SymbolType.CLASS) {
					out.println("- **Class " + item.category().name() + "**: `" + item.symbol() + "`"
							+ (item.details() != null && item.details().reason() != null ? " (" + item.details().reason() + ")" : ""));
				} else {
					String memberPart = item.symbol().substring(item.symbol().indexOf('#') + 1);
					String migration = item.migrationHint() != null
							? " \u2192 Superseded by `" + item.migrationHint().replacementSymbol() + "`"
							: "";
					out.println("- `" + memberPart + "` (" + item.category().name() + ")" + migration);
				}
			}
			out.println();
		}
	}
}
